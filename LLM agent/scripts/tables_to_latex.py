def esc(s: str) -> str:
    return (
        str(s)
        .replace("\\", "\\textbackslash{}")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("_", "\\_")
        .replace("#", "\\#")
    )


def fmt(x: float | str | None, digits: int = 4) -> str:
    if x is None or (isinstance(x, float) and pd.isna(x)):
        return "---"
    if isinstance(x, str):
        if not x or x.upper() == "TODO":
            return "TODO"
        try:
            return f"{float(x):.{digits}f}"
        except ValueError:
            return x
    return f"{float(x):.{digits}f}"


def write_table(path: Path, caption: str, label: str, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    content = f"""% Auto-generated by tables_to_latex.py — do not edit by hand
\\begin{{table}}[!t]
\\centering
\\caption{{{esc(caption)}}}
\\label{{{label}}}
{body}
\\end{{table}}
"""
    path.write_text(content, encoding="utf-8")
    print(f"[tables] Wrote {path.name}")


def table_phase1(out_dir: Path) -> None:
    src = DATA_EXP / "phase1_param_search.json"
    if not src.exists():
        print(f"[tables] Skip phase1: missing {src}")
        return
    data = json.loads(src.read_text(encoding="utf-8"))
    rows = []
    for ext, info in data.get("extractors", {}).items():
        best = info.get("best", {})
        rows.append(
            (
                ext.upper(),
                best.get("label", "---"),
                best.get("n_features", "---"),
                fmt(best.get("score")),
            )
        )
    lines = [
        "\\begin{tabular}{@{}llcc@{}}",
        "\\toprule",
        "Extractor & Best config & Dim & Score \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(f"{esc(r[0])} & {esc(r[1])} & {r[2]} & {r[3]} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_table(
        out_dir / "phase1_params.tex",
        "Phase 1 optimal feature extractor parameters.",
        "tab:phase1",
        "\n".join(lines),
    )


