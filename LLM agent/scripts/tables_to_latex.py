def table_stats_top5(out_dir: Path) -> None:
    src = DATA_EXP / "stats_top5.csv"
    if not src.exists():
        p2 = DATA_EXP / "phase2_all_modes_metrics.csv"
        rows = []
        if p2.exists():
            df2 = pd.read_csv(p2)
            split = df2[df2["eval_mode"] == "split"].copy()
            candidates = [
                ("KNN", "Full(opt)", "KNN Full(opt)"),
                ("SVM", "Full(opt)", "SVM Full(opt)"),
                ("KNN", "D — HOG", "KNN HOG"),
                ("SVM", "D — HOG", "SVM HOG"),
                ("RF", "Full(opt)", "RF Full(opt)"),
            ]
            for model, fs, label in candidates:
                sub = split[(split["model"] == model) & (split["feature_set"] == fs)]
                if not sub.empty:
                    rows.append(
                        {
                            "model": label,
                            "f1_macro": sub.iloc[0]["f1_macro"],
                            "ci_low": "",
                            "ci_high": "",
                            "kappa": "",
                            "mcnemar_p": "",
                            "friedman_rank": "",
                        }
                    )
        df_out = pd.DataFrame(rows)
    else:
        df_out = pd.read_csv(src)

    lines = [
        "\\begin{tabular}{@{}lcccccc@{}}",
        "\\toprule",
        "Model & F1 & CI low & CI high & $\\kappa$ & McNemar $p$ & Rank \\\\",
        "\\midrule",
    ]
    for _, row in df_out.iterrows():
        lines.append(
            f"{esc(row.get('model', ''))} "
            f"& {fmt(row.get('f1_macro') if row.get('f1_macro') != '' else None)} "
            f"& {row.get('ci_low', '---') or '---'} "
            f"& {row.get('ci_high', '---') or '---'} "
            f"& {row.get('kappa', '---') or '---'} "
            f"& {row.get('mcnemar_p', '---') or '---'} "
            f"& {row.get('friedman_rank', '---') or '---'} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_table(
        out_dir / "stats_top5.tex",
        "Unified statistical validation for top Phase~2 models (populate stats\\_top5.csv after bootstrap/McNemar/Friedman runs).",
        "tab:stats",
        "\n".join(lines),
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="Output directory for .tex tables",
    )
    args = parser.parse_args()
    table_phase1(args.out)
    table_phase2_models(args.out)
    table_phase2_top10(args.out)
    table_stats_top5(args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
