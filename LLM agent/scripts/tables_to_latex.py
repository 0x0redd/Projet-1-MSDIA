def table_ablation(out_dir: Path) -> None:
    src = DATA_EXP / "phase3_all_metrics.csv"
    if not src.exists():
        src = PROJECT_ROOT.parent / "results" / "phase3_all_metrics.csv"
    if not src.exists():
        return
    df = pd.read_csv(src)
    split = df[df["eval_mode"] == "split"].set_index("model")

    def f1(model: str) -> float | None:
        if model not in split.index:
            return None
        return float(split.loc[model, "f1_macro"])

    hybrid_scores = [
        f1("cnn_glcm"),
        f1("lbpnet"),
        f1("waveletcnn"),
        f1("cnn_hog"),
    ]
    hybrid_scores = [s for s in hybrid_scores if s is not None]
    best_hybrid_f1 = max(hybrid_scores) if hybrid_scores else 0.0

    rows = [
        ("CNN only (VGG16)", "---", "---", "---", "---", f1("vgg16"), "baseline"),
        ("CNN+GLCM", "\\checkmark", "---", "---", "---", f1("cnn_glcm"), "hybrid"),
        ("CNN+LBP", "---", "\\checkmark", "---", "---", f1("lbpnet"), "hybrid"),
        ("CNN+DWT", "---", "---", "\\checkmark", "---", f1("waveletcnn"), "hybrid"),
        ("CNN+HOG", "---", "---", "---", "\\checkmark", f1("cnn_hog"), "hybrid"),
        ("All branches", "\\checkmark", "\\checkmark", "\\checkmark", "\\checkmark", f1("multibranch_fusion"), "hybrid"),
    ]

    lines = [
        "\\begin{tabular}{@{}lcccccc@{}}",
        "\\toprule",
        "Model & GLCM & LBP & DWT & HOG & F1 & $\\Delta$F1 \\\\",
        "\\midrule",
    ]
    for label, glcm, lbp, dwt, hog, score, kind in rows:
        if score is None:
            delta = "---"
            score_s = "\\textbf{TODO}"
        elif kind == "baseline":
            delta = "---"
            score_s = fmt(score)
        else:
            delta = fmt(score - best_hybrid_f1)
            score_s = (
                f"\\textbf{{{fmt(score)}}}"
                if score == best_hybrid_f1
                else fmt(score)
            )
        lines.append(
            f"{esc(label)} & {glcm} & {lbp} & {dwt} & {hog} & {score_s} & {delta} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_table(
        out_dir / "ablation_features.tex",
        "Feature-branch ablation (held-out split). CNN-only baseline uses Tier-0 VGG16 until dedicated run completes.",
        "tab:ablation",
        "\n".join(lines),
    )


